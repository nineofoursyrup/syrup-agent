// Positional {0}/{1} interpolation. Values are inserted verbatim — a caller
// passing model output must esc() it first, exactly as it does everywhere else.
function tr(key, ...args){
  const pair = STR[key];
  // A missing key returns the key itself rather than "" or undefined: a visible
  // "mem.newThing" on the page is a bug you fix in one minute, an invisible
  // blank is one you ship. test_i18n.py catches it before that, in CI.
  if (!pair) return key;
  const s = pair[LANG === "en" ? 1 : 0];
  return args.length ? s.replace(/\{(\d+)\}/g, (m, i) => args[i] ?? m) : s;
}

// Switch language and repaint everything at once. Every surface rebuilds from
// tr() on render, so there is exactly one thing to do here: flip the flag and
// redraw. `animating` is cleared first because render() deliberately refuses to
// rebuild the Overview mid-animation — without that, a click on 中文 during a
// live turn changed the sidebar and left the chart in the other language.
function setLang(lang){
  LANG = lang === "en" ? "en" : "zh";
  localStorage.setItem("syrup_lang", LANG);
  document.documentElement.lang = LANG === "en" ? "en" : "zh-CN";
  applyStaticI18n();
  if (typeof animating !== "undefined") animating = false;
  if (typeof render === "function") render();
  if (typeof syncChatLogs === "function") syncChatLogs();
  if (typeof tickLive === "function") tickLive();
}

// index.html is static markup, so its strings can't come from a tr() call at
// render time. They carry the key as an attribute instead and this walks them
// once per language change (and once at boot).
//   data-i18n       -> element text
//   data-i18n-html  -> element innerHTML (for the few that carry markup)
//   data-i18n-ph    -> placeholder
//   data-i18n-title -> title
function applyStaticI18n(){
  document.querySelectorAll("[data-i18n]").forEach(el => el.textContent = tr(el.dataset.i18n));
  document.querySelectorAll("[data-i18n-html]").forEach(el => el.innerHTML = tr(el.dataset.i18nHtml));
  document.querySelectorAll("[data-i18n-ph]").forEach(el => el.placeholder = tr(el.dataset.i18nPh));
  document.querySelectorAll("[data-i18n-title]").forEach(el => el.title = tr(el.dataset.i18nTitle));
  document.querySelectorAll("[data-lang-btn]").forEach(el =>
    el.classList.toggle("on", el.dataset.langBtn === LANG));
}
